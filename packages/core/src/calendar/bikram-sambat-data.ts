/**
 * Bikram Sambat (BS / Nepali calendar) days-per-month lookup table.
 *
 * Each entry is `[days_M01, days_M02, ..., days_M12]` for the BS year.
 * BS months are non-deterministic (depend on astronomical observation),
 * so a lookup table is the only correct way to compute them.
 *
 * **Anchor (exact)**: BS 2000-01-01 ↔ AD 1943-04-14.
 *
 * **Status**: This is a starter table covering BS 2000–2099. Conversions
 * relative to the epoch are exact. Some individual year totals (and hence
 * AD dates further from the epoch) may differ by ±1–3 days from the latest
 * official Government of Nepal Patro. For production use that requires
 * pixel-perfect agreement with the current-year Patro, override entries by
 * passing a custom {@link CalendarSystem} that uses your own table.
 *
 * The table is structured so corrections are localised: only the affected
 * year row needs updating; nothing else changes.
 */

