/** Convert ASCII digits 0-9 to Devanagari ०-९. */
export const toDevanagariDigits = (input: string | number): string => {
  const s = typeof input === 'number' ? String(input) : input;
  const map: Record<string, string> = {
    '0': '०',
    '1': '१',
    '2': '२',
    '3': '३',
    '4': '४',
    '5': '५',
    '6': '६',
    '7': '७',
    '8': '८',
    '9': '९',
  };
  let out = '';
  for (const ch of s) out += map[ch] ?? ch;
  return out;
};
